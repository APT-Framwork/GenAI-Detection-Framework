#!/usr/bin/env bash
#
# CAVIX mobile dev launcher.
#
# What it does:
#   1. Resolves the dev host's LAN IP (wlan0 by default, override via
#      CAVIX_LAN_IF or CAVIX_LAN_IP).
#   2. Writes apps/mobile/.env with EXPO_PUBLIC_API_URL pointing at
#      http://<lan-ip>:8000 so Expo Go on a real device can reach the
#      backend running on the laptop.
#   3. Verifies the host API on :8000 is reachable on that IP (warns
#      otherwise; doesn't bail because the API may not be up yet).
#   4. Renders the Expo Go QR code as ANSI to the terminal AND saves a
#      PNG at /tmp/cavix-expo-qr.png that the user can open separately.
#   5. Starts `npx expo start --lan` in the foreground so Metro logs are
#      visible. Ctrl+C stops it cleanly.
#
# Usage:
#   bash infra/scripts/mobile_dev.sh                 # auto-detect LAN IP
#   CAVIX_LAN_IF=eth0  bash infra/scripts/mobile_dev.sh
#   CAVIX_LAN_IP=192.168.1.42 bash infra/scripts/mobile_dev.sh
#   CAVIX_TUNNEL=1     bash infra/scripts/mobile_dev.sh   # use ngrok tunnel
#
# Requires: qrencode (apt install qrencode), Node + npx, mobile deps installed.

set -euo pipefail

# ---- locate repo -----------------------------------------------------
SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
REPO_ROOT=$(cd "${SCRIPT_DIR}/../.." && pwd)
MOBILE_DIR="${REPO_ROOT}/apps/mobile"

if [[ ! -d "${MOBILE_DIR}/node_modules" ]]; then
  echo "❌ apps/mobile/node_modules not found. Run 'cd apps/mobile && npm install' first." >&2
  exit 1
fi

# ---- resolve LAN IP --------------------------------------------------
DEFAULT_IF="${CAVIX_LAN_IF:-wlan0}"

resolve_ip() {
  if [[ -n "${CAVIX_LAN_IP:-}" ]]; then
    echo "${CAVIX_LAN_IP}"
    return
  fi
  # Try the requested interface; fall back to the first non-loopback IPv4.
  local ip
  ip=$(ip -4 -o addr show "${DEFAULT_IF}" 2>/dev/null \
        | awk '{print $4}' | cut -d/ -f1 | head -n1)
  if [[ -z "${ip}" ]]; then
    ip=$(ip -4 -o addr show 2>/dev/null \
          | awk '$2!="lo"{print $4}' | cut -d/ -f1 | head -n1)
  fi
  if [[ -z "${ip}" ]]; then
    echo "❌ Could not resolve a LAN IP. Set CAVIX_LAN_IP=… and retry." >&2
    exit 1
  fi
  echo "${ip}"
}

LAN_IP=$(resolve_ip)
EXPO_URL="exp://${LAN_IP}:8081"
API_URL="http://${LAN_IP}:8000"

echo "▶ CAVIX mobile dev launcher"
echo "  LAN IP        : ${LAN_IP}"
echo "  API endpoint  : ${API_URL}"
echo "  Expo Go URL   : ${EXPO_URL}"

# ---- write .env so the app talks to the right API --------------------
ENV_FILE="${MOBILE_DIR}/.env"
cat > "${ENV_FILE}" <<EOF
# Auto-generated by infra/scripts/mobile_dev.sh
EXPO_PUBLIC_API_URL=${API_URL}
EOF
echo "✓ Wrote ${ENV_FILE}"

# ---- API reachability check (non-fatal) ------------------------------
if command -v curl >/dev/null 2>&1; then
  api_status=$(curl -s -o /dev/null -w "%{http_code}" --max-time 3 \
                 "${API_URL}/health" || true)
  if [[ "${api_status}" == "200" ]]; then
    echo "✓ API reachable at ${API_URL}/health"
  else
    echo "⚠ API not reachable at ${API_URL}/health (status=${api_status:-timeout})."
    echo "  Start the backend with: make host-up   (or honcho -f Procfile.host start)"
  fi
fi

# ---- render QR code --------------------------------------------------
QR_PNG=/tmp/cavix-expo-qr.png

if command -v qrencode >/dev/null 2>&1; then
  echo
  echo "▼ Scan with the iPhone Camera app (Expo Go must be installed)"
  echo
  qrencode -t ANSIUTF8 "${EXPO_URL}"
  qrencode -o "${QR_PNG}" -s 10 -m 4 "${EXPO_URL}"
  echo "  (PNG also saved to ${QR_PNG})"
else
  echo "⚠ qrencode not installed — install with: sudo apt-get install -y qrencode"
  echo "  Without it, open Expo Go and enter URL manually: ${EXPO_URL}"
fi

# ---- launch expo -----------------------------------------------------
cd "${MOBILE_DIR}"

EXPO_FLAGS="--lan"
if [[ "${CAVIX_TUNNEL:-0}" == "1" ]]; then
  EXPO_FLAGS="--tunnel"
  echo "▶ Starting Expo in tunnel mode (CAVIX_TUNNEL=1)"
else
  echo "▶ Starting Expo on LAN (set CAVIX_TUNNEL=1 to route via ngrok)"
fi
echo "  Press 'r' in this terminal to reload, Ctrl+C to stop."
echo

exec npx expo start ${EXPO_FLAGS}
